/**
 * Builds the shared website and application assets.
 *
 * esbuild is the bundler for both JavaScript and CSS; dart-sass is wired in as a
 * plugin so `.scss` files can be imported from anywhere in the graph. Nothing here
 * touches instance data. Output lands in ./dist; UmbracoAppHost includes it in the
 * common .NET build.
 *
 * Usage:
 *   node build.mjs              production build (minified, external source maps)
 *   node build.mjs --dev        unminified build with inline source maps
 *   node build.mjs --dev --watch  rebuild on change
 *   node build.mjs --clean      delete ./dist and exit
 */

import * as esbuild from 'esbuild';
import * as sass from 'sass';
import postcss from 'postcss';
import autoprefixer from 'autoprefixer';
import { rm, mkdir, readdir } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Deletes everything inside `dir`, but not `dir` itself.
 *
 * Removing the directory outright fails with EBUSY on Windows whenever anything
 * holds a handle on it -- an open Explorer window, a shell sitting in it, or a
 * previous `npm run watch`. Emptying it instead is equivalent for our purposes
 * and does not fight the OS.
 *
 * @param {string} dir
 * @returns {Promise<void>}
 */
async function emptyDir(dir) {
  await mkdir(dir, { recursive: true });
  const entries = await readdir(dir);
  await Promise.all(entries.map((entry) => rm(join(dir, entry), { recursive: true, force: true })));
}

const root = import.meta.dirname;
const srcDir = resolve(root, 'src');
const outDir = resolve(root, 'dist');
const nodeModules = resolve(root, 'node_modules');

const args = new Set(process.argv.slice(2));
const dev = args.has('--dev');
const serve = args.has('--serve');
const watch = args.has('--watch') || serve;

/**
 * Browsers to compile down to. Kept deliberately conservative -- this drives both
 * the JavaScript syntax level and esbuild's CSS lowering. Autoprefixer reads the
 * separate `browserslist` key in package.json for vendor prefixes.
 */
const target = ['es2017', 'chrome60', 'firefox60', 'safari12', 'ios12', 'edge79'];

/**
 * Compiles `.scss` through dart-sass, then autoprefixer, and hands the result to
 * esbuild as plain CSS.
 *
 * `resolveDir` is set to the directory of the .scss file so that any `@import` or
 * `url()` still present in the compiled output is resolved by esbuild relative to
 * the right place.
 *
 * @type {esbuild.Plugin}
 */
const sassPlugin = {
  name: 'sass',
  setup(build) {
    build.onLoad({ filter: /\.scss$/ }, async (file) => {
      try {
        const compiled = sass.compile(file.path, {
          loadPaths: [dirname(file.path), srcDir, nodeModules],
          style: 'expanded',
          sourceMap: false,
          // Our partials share variables through @import.
          silenceDeprecations: ['import'],
        });

        const processed = await postcss([autoprefixer]).process(compiled.css, {
          from: file.path,
          map: false,
        });

        return {
          contents: processed.css,
          loader: 'css',
          resolveDir: dirname(file.path),
          // Tell esbuild's watcher about every partial Sass actually read, so
          // editing a partial triggers a rebuild.
          watchFiles: compiled.loadedUrls
            .filter((url) => url.protocol === 'file:')
            .map((url) => fileURLToPath(url)),
        };
      } catch (error) {
        const message = error instanceof Error ? error.message : String(error);
        return { errors: [{ text: message, detail: error }] };
      }
    });
  },
};

const banner = [
  '/*',
  ' * Generated by Frontend/ in the UmbracoAppHost repository -- DO NOT EDIT THIS FILE BY HAND.',
  ' * Edit the sources in Frontend/src, then run:',
  ' *   npm run build',
  ' */',
].join('\n');

/** @type {esbuild.BuildOptions} */
const options = {
  absWorkingDir: root,
  entryPoints: {
    // The website family: one stylesheet and one script.
    'scripts/site': 'src/website/js/site.js',
    'css/site': 'src/website/css/site.css',
    // The application family: one stylesheet and one script, no jQuery.
    'scripts/app': 'src/app/js/app.js',
    'css/app': 'src/app/css/app.css',
  },
  outdir: 'dist',
  bundle: true,
  // Root-absolute URLs in CSS (`url('/media/...')`) are paths the web server resolves
  // at runtime, not build inputs, so esbuild must leave them verbatim instead of
  // trying to find them on disk. These are the roots Umbraco serves.
  //
  // Keep this list explicit. A bare `/*` also matches the internal paths esbuild
  // resolves imports to, which silently externalises the entire dependency graph and
  // reduces every bundle to a stub.
  external: ['/media/*', '/css/*', '/scripts/*', '/App_Plugins/*', '/umbraco/*'],
  format: 'iife',
  target,
  treeShaking: true,
  minify: !dev,
  sourcemap: dev ? 'inline' : 'linked',
  // Keep third-party licence banners in the output -- several of these libraries
  // are MIT and require the notice to travel with the code.
  legalComments: 'eof',
  banner: { js: banner, css: banner },
  plugins: [sassPlugin],
  metafile: true,
  logLevel: 'info',
};

/**
 * Prints the size of each emitted file.
 *
 * @param {esbuild.Metafile} metafile
 */
function report(metafile) {
  const rows = Object.entries(metafile.outputs)
    .filter(([file]) => !file.endsWith('.map'))
    .map(([file, out]) => [relative(root, resolve(root, file)), out.bytes])
    .sort(([a], [b]) => a.localeCompare(b));

  const width = Math.max(...rows.map(([file]) => file.length));
  for (const [file, bytes] of rows) {
    console.log(`  ${file.padEnd(width)}  ${(bytes / 1024).toFixed(1).padStart(7)} kB`);
  }
  console.log(`\n${dev ? 'Development' : 'Production'} build complete. The .NET build packages dist/ for UmbracoAppHost.`);
}

if (args.has('--clean')) {
  await emptyDir(outDir);
  console.log('Emptied dist/');
  process.exit(0);
}

await emptyDir(outDir);

if (watch) {
  const context = await esbuild.context(options);

  // Shut the context down on termination. Without this, esbuild's watch/serve child
  // keeps running -- and keeps port 8000 bound -- after the parent npm process is
  // killed, leaving an orphaned node instance behind.
  let closing = false;
  /** @param {string} signal */
  const shutdown = (signal) => {
    if (closing) {
      return;
    }
    closing = true;
    console.log(`\n${signal} received, shutting down.`);
    context
      .dispose()
      .catch(() => {})
      .finally(() => process.exit(0));
  };

  for (const signal of ['SIGINT', 'SIGTERM', 'SIGHUP', 'SIGBREAK']) {
    process.on(signal, () => shutdown(signal));
  }

  await context.watch();

  if (serve) {
    // Bound to loopback deliberately rather than esbuild's default 0.0.0.0 -- this
    // is a local preview, not something to expose on the network.
    // esbuild returns `hosts` (an array); older releases returned a single `host`.
    const server = await context.serve({ servedir: root, host: '127.0.0.1', port: 8000 });
    const host = server.hosts?.[0] ?? '127.0.0.1';
    console.log(`\nPreview:  http://${host}:${server.port}/demo/pages/website/WebsiteLayout.html (run npm run templates first)`);
    console.log('Rebuilds on save. Ctrl+C to stop.');
  } else {
    console.log('Watching for changes... (Ctrl+C to stop)');
  }
} else {
  const result = await esbuild.build(options);
  report(result.metafile);
}
